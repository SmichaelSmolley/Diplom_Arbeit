# Abtastrate festlegen
fs = 953.5

def calculate_psd(data_list, sample_rate):
    data_arr = np.array(data_list)
    N = len(data_arr)
    window = np.hanning(N)
    windowed = data_arr * window
    
    fft_vals = np.fft.rfft(windowed)
    freqs = np.fft.rfftfreq(N, d=1/sample_rate)
    
    psd_vals = (np.abs(fft_vals) ** 2) / (sample_rate * np.sum(window ** 2))
    psd_vals[1:-1] *= 2
    
    return freqs[1:], psd_vals[1:]

